def normalize_place_type(subtype: str | None) -> str:
    value = (subtype or "").strip()
    if not value:
        return "سایر"
    if value in _TYPE_MAP:
        return value
    if value in _ALIASES:
        return _ALIASES[value]
    # تطبیق واژه‌ای برای داده‌های قدیمی و نام‌های آزاد
    checks = (
        (("مسجد", "نمازخانه", "مذهبی"), "مسجد/مکان مذهبی"),
        (("مدرسه", "دبستان", "دبیرستان", "هنرستان"), "مدرسه"),
        (("مهد",), "مهدکودک"),
        (("دانشگاه",), "دانشگاه"),
        (("آموزشکده",), "آموزشکده"),
        (("بیمارستان",), "بیمارستان"),
        (("داروخانه",), "داروخانه"),
        (("درمانگاه", "کلینیک"), "درمانگاه"),
        (("بهداشت",), "مرکز بهداشت"),
        (("پلیس", "کلانتری", "انتظامی"), "کلانتری/پلیس"),
        (("آتش",), "آتش‌نشانی"),
        (("دادگاه", "دادگستری"), "دادگاه"),
        (("پست",), "اداره پست"),
        (("بانک",), "بانک"),
        (("شهرداری",), "شهرداری/ساختمان دولتی"),
        (("اداره", "دولتی"), "اداره دولتی"),
        (("پارک", "بوستان"), "پارک"),
        (("ورزش", "استادیوم"), "ورزشگاه/مجموعه ورزشی"),
        (("بازار", "خرید"), "بازار/مرکز خرید"),
        (("کتابخانه",), "کتابخانه"),
        (("فرهنگ",), "فرهنگسرا"),
        (("هلال", "امداد"), "پایگاه امداد/هلال احمر"),
    )
    for words, standard in checks:
        if any(word in value for word in words):
            return standard
    return value


def get_place_type_meta(subtype: str | None) -> dict:
    normalized = normalize_place_type(subtype)
    meta = _TYPE_MAP.get(normalized)
    if meta:
        return dict(meta)
    # نوع سفارشی کاربر همچنان آیکون و مسئول عمومی دارد.
    return {"label": normalized or "سایر", "icon": "📍", "role_label": "مسئول مکان"}


def get_place_icon(subtype: str | None) -> str:
    return get_place_type_meta(subtype)["icon"]


def get_place_role_label(subtype: str | None) -> str:
    return get_place_type_meta(subtype)["role_label"]


def supported_place_labels() -> list[str]:
    return [item[0] for item in PLACE_TYPE_DEFINITIONS]
